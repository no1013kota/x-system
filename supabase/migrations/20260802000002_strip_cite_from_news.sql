-- T-M8-06: 保存済みニュースから引用タグ（`<cite index="...">`）を取り除く。
--
-- Web検索を使う実行では Anthropic が `<cite index="43-1">…</cite>` を JSON文字列の中へ混ぜてくる。
-- 生成側は T-M7-20 で対処していたが**ニュース取得側は未対応**で、タグがそのまま画面に出ていた
-- （2026-08-02、ニュース一覧の実データで確認）。取得側は同コミットで直したが、それは
-- 「これから保存される分」にしか効かない。**既に見えているものは消えない**ので、ここで直す。
--
-- **`\b` を使わないこと。** Postgres の正規表現で `\b` は単語境界ではなくバックスペース文字で、
-- 最初に書いた版は1件も置換しない無言の no-op だった（適用後に実データを数えて発覚）。
-- 単語境界が要るなら `\y`。ここは直後に `[^>]*>` が続くので境界指定自体が不要。
--
-- 冪等。タグを含まない行には触れない。
update news_items
   set title = btrim(regexp_replace(title, '</?cite[^>]*>', '', 'gi')),
       summary = btrim(regexp_replace(summary, '</?cite[^>]*>', '', 'gi'))
 where title ~* '</?cite' or summary ~* '</?cite';
