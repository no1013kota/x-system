-- AIクレジットの粒度を100倍にしたことに伴う、消費済みカウントのリセット（T-M8-325）。
--
-- 1クレジット = 1円相当 → **0.01円相当**へ変えた（金額は同じ、粒度だけ100倍）。
-- そのため `usage_counters.ai_credits_used` に旧単位の値が残ると、
-- **100分の1しか使っていないことになる**（例: 92 は新単位では 9,200 相当）。
--
-- 運営者の決定（2026-08-27・案2）: **世代を進めて0から数え直す**。
-- 100倍する案（案1）ではなくこちらを選んだ理由は、単位の混在を残さないことと、
-- 検証（本番スモーク）で消費した分をここで清算できること。
--
-- 世代を進めると期間キーが `YYYY-MM-DD#N` へ変わり、新しい行が0から始まる
-- （`usage_events` の台帳は残るので原価の追跡はできる・T-M8-299）。
update profiles
   set usage_epoch = usage_epoch + 1
 where exists (
   select 1 from usage_counters c where c.user_id = profiles.id
 );

comment on column profiles.usage_epoch is
  '利用枠のリセット世代。期間キーへ `#N` として付く（T-M8-299）。2026-08-27にクレジットの単位変更（1円→0.01円相当）で全員+1した（T-M8-325）。';
