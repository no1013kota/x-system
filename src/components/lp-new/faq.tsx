/**
 * 回答の中の「…」と（…）を語の途中で折らない。文節折り（BudouX）は「」や（）の中も切るので、
 * 「下／書きまで」（1280px・390px の両方）や「X（旧／Twitter）」と、開示語や補足の途中で折れていた
 * （レビュー 2026-09-05 2周目）。`grow.tsx`・`tour.tsx` と同じく inline-block の span で括る。
 * 括弧の直前の英字（「X（旧Twitter）」の X）も一緒に括り、「X」だけが行末に残らないようにする。
 * 回答は文字列のまま（`landing-page.test.ts` が文字列リテラルを集めて開示語を検査するため、JSX に割らない）。
 */
const UNBREAKABLE = /([A-Za-z]*（[^）]*）|「[^」]*」)/;

function withUnbreakableQuotes(text: string) {
  return text
    .split(UNBREAKABLE)
    .filter((part) => part !== "")
    .map((part, i) =>
      UNBREAKABLE.test(part) ? (
        <span className="inline-block" key={i}>
          {part}
        </span>
      ) : (
        part
      ),
    );
}

